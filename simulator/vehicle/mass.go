package vehicle

// -----------------------------------------------------------------------------
// Продольная раскладка масс ступени.
//
// Зачем. Центр масс до этого считался так, будто топливо равномерно размазано
// по ВСЕЙ длине ступени с центром ровно посередине, и по мере выработки не
// двигалось вовсе — двигался только вес, приходящийся на камеры у хвоста.
// Направление смещения при этом получалось верное (к хвосту), а величина —
// заниженной, и главное: топливо в баке ведёт себя не так.
//
// Настоящее топливо занимает не всю длину, а объём баков, и по мере расхода
// его собственный центр тяжести ползёт. Под тягой жидкость прижата к днищу
// бака (осадка), и опустевающий бак тянет центр масс ВНИЗ, к хвосту; на
// пассивном участке осадки нет, жидкость расходится по объёму, и её центр
// возвращается к середине бака. Тот же признак осадки уже есть в модели бака
// (Tank.Settled) и используется для расчёта давления на заборнике — здесь он
// применяется к той же физической величине, а не заводится заново.
//
// Величина расхождения не косметическая: при полных баках центр масс уходит
// к хвосту заметно дальше, чем давала прежняя формула, а значит плечо от
// центра масс до плоскости качания камер — короче. Прежняя модель давала
// ступени управляющий момент, которого у неё нет.
// -----------------------------------------------------------------------------

// Span — отрезок вдоль продольной оси, м от НОСА (Top ближе к носу,
// Bottom — к хвосту, Bottom > Top).
type Span struct{ Top, Bottom float64 }

// Height возвращает высоту отрезка, м.
func (s Span) Height() float64 { return s.Bottom - s.Top }

// Center возвращает середину отрезка, м от носа.
func (s Span) Center() float64 { return (s.Top + s.Bottom) / 2 }

// Доли длины ступени, которые занимает не бак.
//
// engineBayFraction — хвостовой отсек: силовая рама, коллекторы и сами камеры
// ниже днища бака окислителя. interBayFraction — межбаковое пространство.
// Обе взяты как типовые доли компоновки, а не подогнаны: точных чертежей у
// модели нет, и притворяться, что есть, было бы хуже, чем честно назвать
// принятую раскладку. Значения влияют только на положение баков внутри
// ступени, а не на её массу или геометрию снаружи.
const (
	engineBayFraction = 0.06
	interBayFraction  = 0.02
)

// TankSpans возвращает положение баков ступени, м от носа.
//
// Раскладка снизу вверх: хвостовой отсек с камерами, бак ОКИСЛИТЕЛЯ, межбак,
// бак ГОРЮЧЕГО, дальше к носу — всё остальное (переходник, решётчатые рули,
// у связки — следующая ступень). Окислитель снизу потому, что он тяжелее:
// при принятом соотношении компонентов на него приходится около трёх
// четвертей массы заправки, и держать эту массу ближе к хвосту — обычное
// решение компоновки.
//
// Если баки в заданные размеры не помещаются (длина ступени меньше суммы
// высот), отрезки сжимаются пропорционально: лучше сдвинутая раскладка, чем
// бак, торчащий за пределы корпуса.
func TankSpans(stage StageConfig, length float64) (ox, fuel Span) {
	if length <= 0 {
		return Span{}, Span{}
	}
	bay := length * engineBayFraction
	inter := length * interBayFraction

	oxH, fuelH := stage.OxTankHeight, stage.FuelTankHeight
	if total := bay + inter + oxH + fuelH; total > length {
		k := (length - bay - inter) / (oxH + fuelH)
		if k < 0 {
			k = 0
		}
		oxH, fuelH = oxH*k, fuelH*k
	}

	ox = Span{Top: length - bay - oxH, Bottom: length - bay}
	fuel = Span{Top: ox.Top - inter - fuelH, Bottom: ox.Top - inter}
	return ox, fuel
}

// LiquidCenter возвращает центр тяжести жидкости в баке, м от носа.
//
// fill — объёмная заполненность (0…1), settled — доля осадки (Tank.Settled):
// единица означает, что жидкость целиком прижата к днищу тягой, ноль — что
// она расходится по объёму бака в невесомости. Между ними — линейный
// переход: точной модели поведения жидкости в частичной невесомости у
// симулятора нет, и выдумывать её здесь незачем — важно, что на работающих
// двигателях центр идёт к днищу, а на пассивном участке возвращается к
// середине бака.
func LiquidCenter(span Span, fill, settled float64) float64 {
	if span.Height() <= 0 {
		return span.Center()
	}
	fill = clamp01(fill)
	settled = clamp01(settled)

	h := span.Height() * fill
	toBottom := span.Bottom - h/2 // осаждённая жидкость: столб у днища
	free := span.Center()         // невесомость: жидкость по всему объёму
	return free + (toBottom-free)*settled
}

func clamp01(v float64) float64 {
	if v < 0 {
		return 0
	}
	if v > 1 {
		return 1
	}
	return v
}

// PropellantCenter возвращает общий центр тяжести топлива ступени, м от носа,
// по массам и заполненности обоих баков. Если топлива нет вовсе, возвращает
// середину бака окислителя — величина в этом случае ни на что не влияет
// (масса нулевая), но обязана оставаться конечной.
func PropellantCenter(ox, fuel Span, oxMass, oxFill, oxSettled,
	fuelMass, fuelFill, fuelSettled float64) float64 {

	total := oxMass + fuelMass
	if total <= 0 {
		return ox.Center()
	}
	oc := LiquidCenter(ox, oxFill, oxSettled)
	fc := LiquidCenter(fuel, fuelFill, fuelSettled)
	return (oxMass*oc + fuelMass*fc) / total
}
