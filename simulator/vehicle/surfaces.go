// -----------------------------------------------------------------------------
// Аэродинамические управляющие поверхности носителя.
//
// У сверхтяжёлого носителя их два набора. На первой ступени — решётчатые рули:
// они раскрываются после разделения и разворачивают ступень к месту посадки.
// На корабле — четыре плавника: два передних у носа и два задних у юбки.
// Ими корабль удерживает угол атаки под семьдесят градусов на входе, летя
// брюхом вперёд и тормозя всей площадью борта.
//
// Связанные оси здесь те же, что и во всей модели: X — вдоль корпуса к носу,
// Y — вправо, Z — вниз, к брюху. Плавник растёт со спины, то есть с −Z:
// наветренная сторона сплошь закрыта плитками, вешать на неё привод негде.
// А нормаль плавника смотрит в поток, то есть в сторону брюха, по +Z.
// -----------------------------------------------------------------------------

// FlapLimit — ход привода плавника от прижатого положения, рад.
//
// Ноль — панель лежит вдоль борта. Отсчёт идёт от этого положения, поэтому
// величина хода определяется тем, где панель сидит на обводе: чтобы подставить
// её потоку, надо развернуть панель от касательной к обшивке до нормали,
// смотрящей в сторону брюха.
//
// Для задней пары, стоящей точно по бортам, этот угол равен ста двадцати
// градусам — отсюда и значение. Передняя пара уведена дальше на подветренную
// сторону, ей до потока не хватает пятнадцати градусов, и на полном раскрытии
// она подставлена с наклоном. Так и должно быть: подветренным расположением
// платят частью силы, зато панель не стоит в плазме.
//
// Ход у всех четырёх один и тот же намеренно. Раскладка потребного момента
// по плавникам считает нулевое требование серединой хода; будь пределы разные,
// в этой середине пары стояли бы под разными углами и создавали бы момент
// на ровном месте, который нечем убрать.
//
// Прежние семьдесят градусов были величиной ниоткуда: нейтраль в модели была
// привязана к потоку, а не к корпусу, и панель на предельном отклонении
// оказывалась подставлена потоку при любом месте навески.
//
// Открытых данных о настоящем ходе привода нет: телеметрия SpaceX углы
// плавников не показывает.
const FlapLimit = 120 * physics.DegToRad

// FlapMount — посадочное место плавника на корпусе корабля.
//
// Отдельный тип нужен, чтобы место навески задавалось один раз. Физике от него
// нужно плечо момента, рисовке — точка на обводе и станция по длине; когда эти
// числа лежали порознь, картинка показывала машину, которую никто не считал:
// в рисовке плавники сидели на 32 и 52 градусах от спины, в модели — на 41
// и 48, а у настоящего корабля они стоят совсем не там.
type FlapMount struct {
	Name string

	// Station — расстояние от среза сопел корабля, м.
	Station float64

	// Azimuth — положение по обводу, рад от спины. Спина — это −Z, брюхо
	// с плитками — +Z. Положительный угол уводит на правый борт.
	Azimuth float64

	// Area — площадь панели, м².
	Area float64

	// Limit — ход привода, рад.
	Limit float64

	// Span и Chord — размах и средняя хорда панели, м. Выводятся из площади
	// и удлинения: у плавников корабля оно около единицы, панели короткие
	// и широкие.
	Span  float64
	Chord float64

	// StowHalf — половина дуги обвода, закрытой прижатой панелью, рад.
	//
	// Величина нужна обеим сторонам. Прижатая панель лежит по касательной,
	// серединой на обшивке; нормаль у неё смотрит по радиусу этой середины —
	// отсюда нейтраль в модели. Рисовке та же величина говорит, куда положить
	// панель и насколько поднять ось навески над бортом.
	StowHalf float64
}

// ShipFlapMounts возвращает посадочные места плавников корабля.
//
// Расстановка по обводу — не выдумка. У ранних кораблей все четыре плавника
// стояли попарно напротив друг друга, через 180 градусов, и передняя пара
// торчала прямо в поток: она задирала нос, и задним плавникам приходилось это
// парировать. Начиная со второго поколения переднюю пару свели примерно
// до 140 градусов и увели на подветренную сторону, где плазмы почти нет.
// Задняя пара так и осталась через 180 градусов — то есть точно по бортам.
//
// Отсюда и углы от спины: у передних 70 градусов на борт, у задних 90.
//
// Станции по длине следуют из плеч момента: передние плавники сидят у самого
// основания носовой части, задние — над юбкой.
func ShipFlapMounts(length, radius float64) []FlapMount {
	// Доли длины от среза сопел. Центр масс пустого корабля принят посередине,
	// поэтому плечи 0.42 и 0.30 дают именно эти станции.
	const (
		forwardStation = 0.92
		aftStation     = 0.20
	)

	const (
		forwardAzimuth = 70 * physics.DegToRad // половина от 140 между парой
		aftAzimuth     = 90 * physics.DegToRad // половина от 180 между парой
	)

	// Удлинение панели: отношение размаха к хорде.
	//
	// Оно меньше единицы: плавник вытянут вдоль корпуса, а не поперёк.
	// У задней панели хорда около семи метров при вылете под четыре, у передней
	// пять с половиной при трёх — это видно на любой съёмке корабля.
	// Пропорция важна не только для вида: чем больше вылет, тем большую дугу
	// обвода панель закрывает прижатой и тем сильнее её концы отходят от борта.
	mount := func(name string, station, azimuth, area, aspect float64) FlapMount {
		span := math.Sqrt(area * aspect)

		// Половина дуги, закрытой прижатой панелью.
		//
		// Панель плоская и жёсткая, поэтому ближе касательной к обшивке она
		// подойти не может — иначе прошла бы сквозь неё. Прижатой она и лежит
		// по касательной, серединой на борту, а концами наружу. Отсюда угол:
		// половина панели видна из оси корабля под этим углом.
		arc := math.Atan(span / (2 * radius))

		return FlapMount{
			Name:     name,
			Station:  station,
			Azimuth:  azimuth,
			Area:     area,
			Limit:    FlapLimit,
			Span:     span,
			Chord:    area / span,
			StowHalf: arc,
		}
	}

	return []FlapMount{
		mount("fwd_left", length*forwardStation, -forwardAzimuth, 16, 0.55),
		mount("fwd_right", length*forwardStation, forwardAzimuth, 16, 0.55),
		mount("aft_left", length*aftStation, -aftAzimuth, 26, 0.60),
		mount("aft_right", length*aftStation, aftAzimuth, 26, 0.60),
	}
}

// ShipFlaps возвращает плавники корабля.
//
// Передние плавники меньше задних и сидят дальше от центра масс: у них плечо
// больше, и работают они в основном на балансировку. Задние крупнее — они же
// несут основную нагрузку при развороте перед посадкой.
//
// Отсчёт угла привычный: ноль — плавник прижат к борту, предел — раскрыт.
// Управление идёт разностью передних и задних.
//
// Нейтраль задаётся местом навески, а не потоком. Раньше она была общей для
// всех четырёх панелей — нормаль прижатого плавника отсчитывалась от брюха
// на весь ход привода, — и получалось, что на предельном отклонении любая
// панель смотрит точно в поток независимо от того, где она сидит. Для задней
// пары, стоящей по бортам, это случайно совпадало; для передней, уведённой
// на подветренную сторону, — нет.
//
// Прижатая панель лежит по хорде обвода, и нормаль у неё смотрит по радиусу
// середины закрытой дуги. Отсюда нейтраль: азимут навески, сдвинутый на
// половину этой дуги в сторону спины.
//
// Следствие честное и заметное: передние панели на полном раскрытии
// подставлены потоку не плашмя, а с наклоном, и дают меньше силы, чем задние
// той же площади. Ровно за это подветренным расположением и платят.
func ShipFlaps(length, radius float64) []physics.ControlSurface {
	// Центр масс пустого корабля принят посередине длины: плечо считается
	// от него, а станции привязок — от среза сопел.
	center := length / 2

	out := make([]physics.ControlSurface, 0, 4)
	for _, m := range ShipFlapMounts(length, radius) {
		// Левый и правый раскрываются каждый в свою сторону, поэтому и ось
		// навески у них противоположна. Не будь этого, все четыре плавника
		// поворачивались бы в одну сторону и создавали бы крен на ровном месте.
		hand := 1.0
		if m.Azimuth < 0 {
			hand = -1
		}

		// Точка навески на обводе. Азимут отсчитан от спины, то есть от −Z.
		sa, ca := math.Sincos(m.Azimuth)

		// Нормаль прижатой панели: радиус середины закрытой ею дуги.
		sn, cn := math.Sincos(m.Azimuth - hand*m.StowHalf)

		out = append(out, physics.ControlSurface{
			Name:          m.Name,
			Area:          m.Area,
			Arm:           physics.Vec3{X: m.Station - center, Y: radius * sa, Z: -radius * ca},
			Neutral:       physics.Vec3{Y: sn, Z: -cn},
			Hinge:         physics.Vec3{X: hand},
			MaxDeflection: m.Limit,
			Rate:          12 * physics.DegToRad,
		})
	}
	return out
}

// GridFins возвращает решётчатые рули первой ступени.
//
// Решётчатый руль — это набор параллельных пластин в рамке. На гиперзвуке
// он работает хуже плоского руля той же площади: ячейки запираются скачками
// уплотнения. Зато он компактен, складывается вдоль борта и не требует
// большого шарнирного момента. Эффективность учтена уменьшенной площадью.
func GridFins(length, radius float64) []physics.ControlSurface {
	// Рули стоят у самого верха ступени: плечо до центра масс максимально.
	x := length * 0.40

	surface := func(name string, angle float64) physics.ControlSurface {
		// Четыре руля по окружности, через девяносто градусов.
		s, c := math.Sincos(angle)
		return physics.ControlSurface{
			Name:          name,
			Area:          4.5,
			Arm:           physics.Vec3{X: x, Y: radius * s, Z: radius * c},
			Neutral:       physics.Vec3{Y: c, Z: -s},
			Hinge:         physics.Vec3{Y: s, Z: c},
			MaxDeflection: 20 * physics.DegToRad,
			Rate:          30 * physics.DegToRad,
		}
	}

	return []physics.ControlSurface{
		surface("fin_1", 0),
		surface("fin_2", math.Pi/2),
		surface("fin_3", math.Pi),
		surface("fin_4", 3*math.Pi/2),
	}
}
