package physics

import "math"

// -----------------------------------------------------------------------------
// Аэродинамические управляющие поверхности.
//
// Решётчатые рули возвращаемой ступени и плавники корабля работают там, где
// качание камер бесполезно: двигатели выключены, а поток есть. Момент они
// создают тот же по природе, что и корпус, — только площадь у них своя,
// плечо своё, и угол к потоку задаёт оператор или автопилот.
//
// На гиперзвуке сила на плоской панели считается по ньютоновской теории
// обтекания:
//
//	Cp = 2·sin²θ
//
// где θ — угол между набегающим потоком и плоскостью панели. Теория проста
// до неприличия — она предполагает, что молекулы газа теряют нормальную
// составляющую импульса и скользят вдоль поверхности, — но на больших числах
// Маха и больших углах атаки даёт точность, которой хватает: именно так
// считают компоновку возвращаемых аппаратов на предварительных этапах.
//
// На малых скоростях она занижает силу, поэтому ниже звука добавляется
// линейный по углу член: там плавники работают как обычное оперение.
// -----------------------------------------------------------------------------

// ControlSurface — управляющая поверхность на корпусе.
type ControlSurface struct {
	// Name — обозначение: "fwd_left", "aft_right" и подобные.
	Name string

	// Area — площадь панели, м².
	Area float64

	// Arm — положение оси навески относительно центра масс в связанных
	// осях, м. Плечо момента считается от него.
	Arm Vec3

	// Neutral — единичная нормаль панели в нейтральном положении,
	// связанные оси.
	Neutral Vec3

	// Hinge — единичный вектор оси вращения панели, связанные оси.
	Hinge Vec3

	// MaxDeflection — предельный угол отклонения от нейтрали, рад.
	MaxDeflection float64

	// Rate — скорость перекладки привода, рад/с.
	Rate float64
}

// Normal возвращает нормаль панели, отклонённой на заданный угол.
func (s ControlSurface) Normal(deflection float64) Vec3 {
	return rotateAboutAxis(s.Neutral, s.Hinge, deflection).Unit()
}

// Force возвращает силу на панели в связанных осях, Н.
//
// airBody — скорость корпуса относительно воздуха в связанных осях. Поток
// в системе корпуса идёт навстречу ей.
func (s ControlSurface) Force(deflection float64, airBody Vec3,
	dynamicPressure, mach float64) Vec3 {

	speed := airBody.Norm()
	if speed < 1e-6 || dynamicPressure <= 0 || s.Area <= 0 {
		return Vec3{}
	}

	// Направление потока в связанных осях.
	flow := airBody.Scale(-1 / speed)
	normal := s.Normal(deflection)

	// Составляющая потока по нормали. Знак говорит, какая сторона панели
	// наветренная, модуль — насколько круто поток на неё падает.
	cos := flow.Dot(normal)
	if math.Abs(cos) < 1e-9 {
		return Vec3{} // панель стоит ребром к потоку
	}

	// Ньютоновское обтекание: Cp = 2·sin²θ, где sin θ и есть |cos| между
	// потоком и нормалью.
	cp := 2 * cos * cos

	// Ниже звука ньютоновская оценка занижает силу: там панель работает
	// как крыло, и подъёмная сила растёт линейно по углу. Добавка сходит
	// на нет к третьему числу Маха.
	if mach < 3 {
		blend := 1 - mach/3
		cp += 2 * math.Pi * math.Abs(cos) * blend * 0.5
	}

	// Сила прижимает панель по потоку: вдоль нормали в ту сторону,
	// куда сносит наветренную сторону.
	magnitude := cp * dynamicPressure * s.Area
	return normal.Scale(magnitude * sign(cos))
}

// Torque возвращает момент панели относительно центра масс, Н·м.
func (s ControlSurface) Torque(deflection float64, airBody Vec3,
	dynamicPressure, mach float64) Vec3 {

	return s.Arm.Cross(s.Force(deflection, airBody, dynamicPressure, mach))
}

// sign возвращает знак числа.
func sign(x float64) float64 {
	if x < 0 {
		return -1
	}
	return 1
}

// rotateAboutAxis поворачивает вектор вокруг оси на заданный угол
// по формуле Родрига.
func rotateAboutAxis(v, axis Vec3, angle float64) Vec3 {
	k := axis.Unit()
	c, s := math.Cos(angle), math.Sin(angle)

	return v.Scale(c).
		Add(k.Cross(v).Scale(s)).
		Add(k.Scale(k.Dot(v) * (1 - c)))
}
