// -----------------------------------------------------------------------------
// Момент розжига посадочного импульса.
//
// Прежняя оценка — кинематический тормозной путь v²/(2a) от ТЕКУЩЕЙ скорости
// — завышала высоту розжига, и не на проценты. Она исходит из того, что до
// самого касания ничего, кроме тяги, скорость не меняет. Для бустера это
// неверно: он спускается двигателями вперёд, тупым торцом, и ниже тридцати
// километров плотность растёт на порядок каждые несколько километров.
// Сопротивление гасит заметную часть скорости САМО, ещё до всякой тяги, —
// и тормозной путь, посчитанный по скорости на большой высоте, описывает
// торможение, которого не потребуется.
//
// Здесь вместо формулы — прямой прогноз до касания. Состояние продвигается
// вперёд тем же шагом и по той же физике, что и полёт: атмосфера по высоте,
// число Маха, ориентация и подставленная потоку площадь (physics.BodyDragArea),
// скоростной напор, расход массы, выход камер на режим, располагаемая тяга
// выбранной группы и переход на меньшие группы. Ищется САМАЯ ПОЗДНЯЯ высота
// розжига, при которой мягкое касание ещё достижимо.
//
// Прогноз ведёт оба канала — вертикальный и горизонтальный: тяга и
// сопротивление гасят их вместе, одним вектором против скорости. Одного
// вертикального недостаточно — бустер приходит к импульсу с горизонтальной
// скоростью того же порядка, и высота, посчитанная по одной вертикали,
// оказывается достаточной ровно настолько, насколько мала горизонталь.
//
// Упрощение осталось одно: тяга считается чисто ретроградной. Наведение
// (G-FOLD) распорядится ею точнее, добавив боковую составляющую на вынос
// в точку, — но потребная тяга от этого только растёт, так что ретроградная
// оценка остаётся нижней границей потребного, а не завышением.
// -----------------------------------------------------------------------------

// ignitionPredictStep — шаг прогноза, с. Крупнее шага полёта: прогноз
// отвечает на вопрос «хватит ли высоты», а не считает траекторию для
// исполнения, и от секунды до касания ошибка порядка десятков метров —
// заведомо мельче самой высоты розжига.
const ignitionPredictStep = 1.0

// ignitionPredictLimit — предел числа шагов прогноза (четверть часа).
const ignitionPredictLimit = 900

// ignitionAlignMax — предел времени, которое прогноз отводит на разворот
// корпуса двигателями вперёд перед импульсом, с. Само время считается по
// ФАКТИЧЕСКИ оставшемуся углу (см. ignitionAlignDelay), а это лишь потолок
// на случай, когда управлять нечем.
const ignitionAlignMax = 20.0

// ignitionSearchFloor — нижняя ступенька поиска высоты розжига, м. Ниже
// неё разговор бессмыслен: на один только разворот корпуса двигателями
// вперёд уходит ignitionAlignTime.
const ignitionSearchFloor = 300.0

// ignitionSearchSteps — сколько ступенек в лестнице поиска. Шестнадцать
// ступенек от трёхсот метров до сотни километров — шаг около 1.4 по
// высоте; между соседними ступеньками ответ доуточняется делением пополам.
const ignitionSearchSteps = 16

// ignitionRefineSteps — сколько делений пополам между соседними ступеньками.
const ignitionRefineSteps = 4

// landingPrediction — итог прогноза посадки от заданной высоты розжига.
type landingPrediction struct {
	// Touchdown — вертикальная скорость касания, м/с (положительная — вниз).
	Touchdown float64

	// PeakDecel — наибольшее замедление за импульс, м/с².
	PeakDecel float64

	// IgnitionDemand — доля располагаемой тяги группы, которую закон
	// требует на ПЕРВОМ шаге импульса. Единица означает, что импульс
	// начинается на упоре: запаса нет ни на ошибку прогноза, ни на
	// боковую коррекцию, ни на удержание ориентации.
	IgnitionDemand float64

	// FuelUsed — израсходованное топливо, кг.
	FuelUsed float64

	// Ran означает, что прогноз пришёл к определённому исходу, а не упёрся
	// в предел шагов. Недошедший прогноз не значит «сядем мягко»: он не
	// значит ничего.
	Ran bool

	// Reached означает, что до розжига дело дошло: с текущей высоты аппарат
	// действительно опустился до заданной.
	Reached bool

	// Stalled — снижение погашено ДО земли: зажгли слишком рано и повисли.
	// Это не жёсткая посадка, а перерасход: исход мягкий, но не поздний.
	Stalled bool

	// Dry — топливо кончилось раньше касания.
	Dry bool

	// Состояние в точке РОЗЖИГА — то, с чем ступень придёт к импульсу,
	// если зажечь на заданной высоте. Из него строится проверка
	// достижимости терминального участка выпуклой задачей (см.
	// booster_plan.go): решать её от ТЕКУЩЕГО состояния бессмысленно —
	// на пассивном участке аппарат ещё в той области, где модель
	// невалидна.
	ArrivalAltitude   float64
	ArrivalVertical   float64
	ArrivalHorizontal float64
	ArrivalMass       float64
	ArrivalGroup      int

	// Состояние в точке ПЕРЕДАЧИ УПРАВЛЕНИЯ терминальному наведению —
	// там, где минимальная тяга группы становится меньше веса и выпуклая
	// задача впервые делается применимой (см. gfoldApplicable). Именно это
	// состояние G-FOLD и унаследует, и именно про него имеет смысл
	// спрашивать «существует ли мягкая посадка».
	HandoverAltitude   float64
	HandoverVertical   float64
	HandoverHorizontal float64
	HandoverMass       float64
	HandoverGroup      int
	HandoverFound      bool

	// HandoverTravel — горизонтальное расстояние, которое ступень пройдёт
	// от ТЕКУЩЕГО положения до точки передачи управления, м. Без него
	// проба терминальной задачи ставила будущий аппарат в нынешнюю точку
	// — на высоте семисот метров, но в сотнях километров от площадки, где
	// ступень находится посреди пассивного участка. Задача выходила
	// неразрешимой всегда, и по этой неразрешимости объявлялся увод.
	HandoverTravel float64

	// MinMargin — наименьший запас по тормозному пути вдоль всего
	// прогноза, м. Отрицательный означает, что где-то на траектории
	// располагаемой тяги уже не хватает.
	MinMargin float64

	// Schedule — последовательность групп камер, которую прогноз назначил.
	Schedule []int
}

// coastAngleOfAttack — угол атаки, которым управление КОМАНДУЕТ лететь на
// пассивном участке: ретроград плюс отклонение, какое помещается в
// располагаемый момент (boosterCoastAoAOffset). Именно им бустер и тормозит
// весь путь от конца разворотного импульса до розжига — своего entry burn у
// него нет. Считается один раз на решение о розжиге, а не внутри прогноза:
// внутри это те же двенадцать вычислений момента на каждый шаг.
//
// ИЗВЕСТНОЕ РАСХОЖДЕНИЕ, замерено и НАМЕРЕННО не исправлено в одиночку.
// Отклонение помещается в располагаемый момент только там, где напора
// почти нет. На пассивном участке команда сходит с 90° до 12…16° по мере
// роста напора (при 85 кПа — 12°), корпус её отрабатывает (фактический
// угол атаки 167…173°), и подставленная потоку площадь оказывается
// 230…400 м² вместо 911 м² у полного тормозного положения. Снимок,
// сделанный на семидесяти километрах, где достижимы все девяносто
// градусов, задаёт прогнозу площадь втрое-вшестеро больше настоящей: на
// этом и разъезжается прицеливание — промах в двести метров на отсечке
// разворотного импульса вырастает к плотным слоям до полутора километров.
//
// Замена снимка на функцию условий полёта (угол атаки на каждом шаге
// прогноза по тому же балансу моментов) убирает именно это расхождение:
// прогнозируемый промах держится 200…360 м весь пассивный участок вместо
// роста до 1600 м. Но одна эта правка ухудшает посадку: с настоящим, вдвое
// меньшим торможением ступень массой 692 т приходит так, что полосы высот,
// на которых тринадцать камер садят её мягко, не существует вовсе —
// минимальный газ группы больше потребной тяги (зависание), а ниже не
// хватает высоты на выход камер на режим (жёсткое касание). Замерено на
// шести зёрнах: касание 7…37 м/с вместо 7…20, остаток топлива 19…335 т
// вместо 325…333, розжиг на тридцати километрах на половине зёрен.
// Уменьшение заправки до 3450 т (масса прибытия 463 т, стартовая группа
// становится пятёркой) картину не спасает: 17…97 м/с и промах 440…997 м.
//
// Порядок исправления поэтому обратный: сначала терминальный участок
// должен перестать зависеть от завышенного торможения (группа розжига по
// диапазону Min/MaxThrottle, а не только по способности остановить;
// полоса допустимых высот шире ступеньки лестницы поиска), и лишь затем
// модель угла атаки приводится к действительности.
func (b *Booster) coastAngleOfAttack(nav orbit.NavState) float64 {
	mach := 0.0
	if ss := physics.Atmosphere(nav.Altitude).SoundSpeed; ss > 0 {
		mach = nav.AirRelativeVelocity.Norm() / ss
	}
	return 180 - b.boosterCoastAoAOffset(nav, retrogradeGroundAttitude(nav), mach)
}

// ignitionAlignDelay — сколько секунд прогноз обязан отдать даром на
// разворот корпуса двигателями вперёд перед розжигом, с.
//
// Считается по ФАКТИЧЕСКИ оставшемуся углу, а не постоянной. Постоянная в
// пятнадцать секунд обходилась дорого: на высоте розжига бустер уже стоит
// ретроградом (косинус между тягой и ретроградом 0.99), доворачивать
// нечего, — а прогноз всё равно платил за разворот пятнадцатью секундами
// свободного падения, то есть на скорости в девятьсот метров в секунду
// добрым десятком километров высоты. Розжиг от этого уезжал вверх ровно на
// эту величину.
//
// Время разворота — по разгонно-тормозному профилю: половину угла
// раскручиваемся с располагаемым угловым ускорением, половину гасим,
// откуда t = 2·√(θ/α). Тот же α, которым пользуется и само наведение
// (reorientAngularAccel).
func (b *Booster) ignitionAlignDelay(nav orbit.NavState) float64 {
	v := nav.GroundRelativeVelocity
	if v.Norm() < 1 {
		return 0
	}
	retro := v.Scale(-1 / v.Norm())
	forward := b.attitude.Orientation.Rotate(physics.Vec3{X: 1})

	theta := math.Acos(physics.Clamp(forward.Unit().Dot(retro), -1, 1))
	alpha := b.reorientAngularAccel()
	if alpha <= 0 {
		return ignitionAlignMax
	}
	return physics.Clamp(2*math.Sqrt(theta/alpha), 0, ignitionAlignMax)
}

// perEngineAt — тяга одной камеры на заданной атмосфере, Н.
func perEngineAt(stage vehicle.StageConfig, atm physics.AtmosphereState) float64 {
	return vehicle.ThrustAtAltitude(stage, atm.Pressure)
}

// descentComponents раскладывает скорость относительно поверхности на
// вертикальную (вниз положительная) и горизонтальную составляющие.
func descentComponents(nav orbit.NavState) (vz, vh float64) {
	up := nav.Position.Unit()
	v := nav.GroundRelativeVelocity
	radial := v.Dot(up)
	return -radial, v.Sub(up.Scale(radial)).Norm()
}

// predictLanding прогоняет движение от текущего состояния до касания:
// свободное снижение с сопротивлением до высоты ignitionAltitude, затем
// выход камер на режим, затем торможение располагаемой тягой с переходом на
// меньшие группы по мере падения потребной тяги.
//
// Каналов два — вертикальный и горизонтальный. Одного вертикального мало:
// бустер приходит к посадочному импульсу с горизонтальной скоростью того же
// порядка, что и вертикальная, тормозит их ОБЕ одной и той же тягой против
// вектора скорости, и высота розжига, посчитанная по одной вертикали,
// оказывается достаточной ровно настолько, насколько мала горизонталь.
// Прогноз с одной вертикалью зажигал в километре над водой и приводил
// ступень к поверхности с сотней метров в секунду — почти целиком
// горизонтальных.
//
// Наведение (G-FOLD) распорядится тягой точнее, чем чистый ретроград:
// у него есть и боковая составляющая на вынос в точку. Но потребная тяга
// от этого только растёт, поэтому ретроградная оценка — нижняя граница
// потребного, а не завышение.
func (b *Booster) predictLanding(nav orbit.NavState,
	ignitionAltitude, aoaCoast, alignTime float64) landingPrediction {
	stage := b.Config.FirstStage
	radius := b.Config.Diameter / 2
	frontal := math.Pi * radius * radius
	side := b.Config.FirstStageLength * b.Config.Diameter
	minThrottle := b.minThrottle()

	dry := b.dryMass()
	fuel := b.propulsion.PropellantMass()
	alt := nav.Altitude
	vz, vh := descentComponents(nav)

	// Ориентация в прогнозе не замораживается на текущей: она сводится к
	// той, которой полёт КОМАНДУЕТ.
	//
	// Замороженный текущий угол атаки давал вот что. На пассивном участке
	// бустер разворачивало от 60° к 152° и обратно, подставленная потоку
	// площадь ходила от 490 до 916 м² (борт против торца — разница почти
	// восьмикратная), и прогнозная высота розжига ходила вместе с ней:
	// 9.3 км, через десять секунд 42.6, ещё через двадцать снова 9.4.
	// Решение о розжиге не может зависеть от того, каким боком ступень
	// повёрнута в данное мгновение за сто секунд до самого розжига.
	aoa0 := b.bodyAngleOfAttack(nav.AirRelativeVelocity)

	// Группа берётся та же, с которой импульс и начнётся.
	// Группа розжига выбирается не заранее, а в момент розжига — по
	// предсказанным массе, скорости и высоте (см. landingIgnitionGroupFor).
	groupIdx := 0
	groupChosen := false

	out := landingPrediction{MinMargin: math.Inf(1)}
	travel := 0.0
	armed := false
	burning := false
	runUp := 0.0

	// applied — тяга, ФАКТИЧЕСКИ достигнутая приводом (м/с²). Прогноз
	// обязан вести её отдельно от команды: между ними стоит запаздывание
	// throttleFilterTime, и на посадочном импульсе длиной в десяток секунд
	// эта постоянная времени — не мелочь, а заметная доля всего манёвра.
	// Прогноз, считающий тягу мгновенной, обещает торможение, которого в
	// первые секунды после розжига ещё нет, и потому назначает розжиг
	// ниже, чем следует; исполнителю остаётся аварийно уходить в полный
	// газ и всё равно не успевать.
	applied := 0.0

	// Прогноз о посадке имеет смысл только на снижении.
	if vz <= 0 {
		return out
	}

	// left — остаток пути до ПЛОСКОСТИ ЗАХВАТА, а alt по-прежнему истинная
	// высота: по ней считаются атмосфера, тяжесть и тяга камер. Путать их
	// нельзя — первая отвечает на «сколько осталось тормозить», вторая на
	// «в каких условиях».
	catchAlt := b.tower.CatchHeight

	for i := 0; i < ignitionPredictLimit; i++ {
		left := alt - catchAlt
		if left <= 0 {
			out.Ran = true
			out.Touchdown = math.Hypot(vz, vh)
			return out
		}
		mass := dry + fuel
		if mass <= 0 {
			return out
		}

		// Розжиг — не мгновенное событие. Сначала корпус надо развернуть
		// двигателями вперёд: тяга, приложенная к лежащей поперёк потока
		// ступени, скорость не гасит, а только заворачивает траекторию.
		// Разворот занимает ignitionAlignTime, и всю эту высоту прогноз
		// обязан отдать даром — иначе он назначает розжиг на километре над
		// водой, где до касания пять секунд, а на один разворот нужно
		// пятнадцать. Ровно это и вышло измерить: розжиг на 900 м,
		// касание на 126 м/с при полном баке.
		// Взведение — по факту, что высота уже ниже назначенной, а НЕ по
		// предсказанию, что шаг её пересечёт.
		//
		// Упреждение на шаг пробовалось и отвергнуто замером: оно делает
		// прогноз оптимистичнее ровно на один шаг пути, то есть на двухстах
		// метрах в секунду — на двести метров высоты. Розжиг съезжал с
		// 750-950 м до 540-700 м, и средняя скорость касания по шести
		// зёрнам ухудшалась с 25 до 64 м/с.
		//
		// Вырожденный случай, ради которого упреждение вводилось (высота
		// розжига меньше пути за один шаг — тогда она проскакивается и
		// импульс не начинается вовсе), закрыт с другой стороны: такие
		// высоты возвращались только при пустых баках, а сухой прогноз
		// теперь отвергается поиском (см. reject).
		if !armed && alt <= ignitionAltitude {
			armed = true
			out.Reached = true

			out.ArrivalAltitude = alt
			out.ArrivalVertical = vz
			out.ArrivalHorizontal = vh
			out.ArrivalMass = mass
			// Группа розжига здесь ЕЩЁ НЕ ВЫБРАНА — её выбирает
			// landingIgnitionGroupFor на первом же шаге с работающими
			// камерами, по фактическим массе, скорости и высоте. Прежде
			// расписание пополнялось прямо здесь, и первым элементом
			// попадал ноль: печаталось «группы [0 5 3]», а стартовая
			// группа в расписании не значилась вовсе.
		}
		if armed && !burning {
			burning = true
			runUp = boosterIgnitionLeadTime
		}

		// Ориентация по участкам: доворот от текущего положения к
		// командному углу пассивного участка, затем сам пассивный угол, а
		// с розжигом — чистый ретроград: тормозить, не выставив тягу
		// против скорости, нельзя.
		//
		// Переключение стоит РАНЬШЕ расчёта сопротивления, и это
		// принципиально. Пока оно стояло после, шаг розжига считал
		// сопротивление по тормозному боковому положению корпуса
		// (~900 м², под сорок м/с² на двадцати километрах) — и по нему же
		// выбирал группу камер. Выходило, что тормозить почти нечего:
		// потребная тяга получалась отрицательной, группа падала сразу до
		// трёх камер, а на следующем же шаге корпус разворачивался
		// двигателями вперёд, сопротивление падало в пять раз, — и
		// необратимо выбранная тройка везла ступень в воду на 400 м/с.
		// Разворот двигателями вперёд идёт с САМОГО НАЧАЛА прогноза, а не
		// от высоты розжига: корпус доворачивается на пассивном участке,
		// задолго до импульса, и к моменту розжига стоит ретроградом
		// (измерено: косинус между тягой и ретроградом 0.99 уже на
		// подходе).
		//
		// Отсчёт разворота ОТ высоты розжига обходился дорого: на двухстах
		// пятидесяти метрах в секунду шесть секунд — это полтора километра
		// падения, и любая ступенька поиска ниже двух километров означала
		// импульс, начинающийся под землёй. Прогноз для таких высот честно
		// сжигал ноль тонн и приводил ступень к воде на 250 м/с, поиск их
		// отвергал — и розжиг уезжал к четырём километрам. Разворота при
		// этом никакого не требовалось: он давно был сделан.
		aoa := 180.0
		if !burning {
			aoa = aoaCoast
			if t := float64(i) * ignitionPredictStep; alignTime > 0 && t < alignTime {
				aoa = aoa0 + (aoaCoast-aoa0)*t/alignTime
			}
		}

		v := math.Hypot(vz, vh)
		if v < 1e-6 {
			v = 1e-6
		}
		atm := physics.Atmosphere(alt)
		mach := 0.0
		if atm.SoundSpeed > 0 {
			mach = v / atm.SoundSpeed
		}
		q := physics.DynamicPressure(atm.Density, v)
		// Прогноз плоский, поперечной оси в нём нет — поэтому
		// аэродинамика раскладывается на две составляющие в ПЛОСКОСТИ
		// траектории: торможение против скорости и подъёмная сила поперёк
		// неё (physics.BodyAeroSplit). Считать всю силу торможением значило
		// бы обещать торможение, которого у отклонённого корпуса нет.
		full := q * physics.BodyDragArea(mach, aoa, frontal, side) / mass
		axialShare, lateralShare := physics.BodyAeroSplit(mach, aoa, frontal, side)
		dragAcc := full * axialShare
		liftAcc := full * lateralShare
		g := physics.GravityMagnitudeAtAltitude(alt)

		thrustAcc := 0.0
		if burning {
			if fuel <= 0 {
				out.Ran = true
				out.Dry = true
				out.Touchdown = math.Inf(1)
				return out
			}
			perEngine := vehicle.ThrustAtAltitude(stage, atm.Pressure)

			// Группа розжига — по фактическим массе, скорости и высоте в
			// момент розжига, а не назначенная заранее.
			if !groupChosen {
				groupChosen = true
				groupIdx = landingIgnitionGroupFor(left, v, mass, perEngine, g, dragAcc)
				out.ArrivalGroup = landingEngineSequence[groupIdx]
			}

			// Потребное замедление вдоль траектории, чтобы прийти к земле
			// со скоростью касания: v² = v_кас² + 2·a·s, где s — остаток
			// ПУТИ, а не остаток высоты (они различаются во столько же
			// раз, во сколько полная скорость больше вертикальной).
			// Это обратная связь по текущему состоянию, а не разомкнутая
			// уставка: прежняя редакция сравнивала скорость с опорным
			// профилем и, пока скорость была НИЖЕ профиля, всё равно
			// командовала торможение — знак получался обратный нужному,
			// снижение гасилось в воздухе, и прогноз не заканчивался
			// ничем до предела шагов.
			path := left * v / vz
			need := (v*v - landingTouchdownSpeed*landingTouchdownSpeed) / (2 * path)

			// Тяжесть вдоль вектора скорости разгоняет ступень; поперёк —
			// заворачивает траекторию, и на торможение не работает.
			gAlong := g * vz / v
			// Сопротивление в план не закладывается — см.
			// landingRequiredThrust: оно падает как квадрат скорости и к
			// концу импульса исчезает, а располагаемая тяга конечна.
			required := (need + gAlong) * mass

			// Переход на меньшую группу — по тому же признаку, что и в
			// полёте (updateLandingEngineGroup): потребная тяга ушла ниже
			// минимума текущей группы, а следующая ещё успевает погасить
			// скорость на оставшемся пути.
			for groupIdx < len(landingEngineSequence)-1 {
				cur := float64(landingEngineSequence[groupIdx])
				next := float64(landingEngineSequence[groupIdx+1])
				if required >= perEngine*cur*minThrottle {
					break
				}
				// Та же доля располагаемого, что и в законе газа ниже:
				// проверять переход по ПОЛНОЙ тяге меньшей группы, а
				// тормозить потом на трёх четвертях — значит разрешать
				// переход, который сам же закон газа исполнить не сможет.
				aNext := perEngine*next/mass - gAlong + dragAcc
				if aNext <= 0 || landingStoppingDistance(v, aNext) > path {
					break
				}
				groupIdx++
			}

			if g := landingEngineSequence[groupIdx]; len(out.Schedule) == 0 ||
				out.Schedule[len(out.Schedule)-1] != g {
				out.Schedule = append(out.Schedule, g)
			}

			n := float64(landingEngineSequence[groupIdx])
			full := perEngine * n / mass

			// Точка передачи управления: минимальная тяга группы стала
			// меньше веса, то есть аппарат впервые способен снижаться на
			// работающих камерах.
			if !out.HandoverFound &&
				minThrottle*full < gfoldDescentMargin*g {
				out.HandoverFound = true
				out.HandoverTravel = travel
				out.HandoverAltitude = alt
				out.HandoverVertical = vz
				out.HandoverHorizontal = vh
				out.HandoverMass = mass
				out.HandoverGroup = landingEngineSequence[groupIdx]
			}

			// Запас по тормозному пути на полной тяге текущей группы.
			if aStop := full - gAlong + dragAcc; aStop > 0 {
				if m := left - landingStoppingDistance(v, aStop)*vz/v; m < out.MinMargin {
					out.MinMargin = m
				}
			} else {
				out.MinMargin = math.Inf(-1)
			}

			// Тяга берётся ВСЯ располагаемая, без резерва.
			//
			// Резерв здесь был и стоил дорого. Прогноз планировал
			// торможение на трёх четвертях располагаемого, и поиск, честно
			// отвечая на свой вопрос, находил ту высоту, с которой хватает
			// СЛАБОГО импульса, — двадцать с лишним километров вместо
			// нескольких. Резерв, заложенный в саму опорную траекторию
			// торможения, перестаёт быть резервом: он становится планом.
			//
			// Самый поздний допустимый розжиг определяется предельными
			// возможностями, а не долей от них. Запас появляется сам:
			// поиск берёт первую подходящую ступеньку лестницы снизу,
			// решение пересчитывается каждую секунду, и на разворот перед
			// импульсом отведено ignitionAlignTime без тяги.
			//
			// Нижний предел — настоящий: ниже minThrottle работающая группа
			// не дросселируется. Это предел привода, и прогноз обязан его
			// видеть, иначе он спланирует то, чего камеры не смогут.
			floor := minThrottle * full

			if out.IgnitionDemand == 0 && full > 0 {
				out.IgnitionDemand = (need + gAlong) / full
			}
			want := physics.Clamp(need+gAlong, floor, full)

			// Выход на режим: пока камеры раскручиваются, тяга ниже
			// номинала. Линейный рост от предела дросселирования — грубо,
			// но честнее, чем считать полную тягу с первого мгновения.
			frac := 1.0
			if runUp > 0 {
				frac = minThrottle + (1-minThrottle)*
					(1-runUp/boosterIgnitionLeadTime)
				runUp -= ignitionPredictStep
				if runUp < 0 {
					runUp = 0
				}
			}
			// Команда — то, что просит закон; тяга идёт к ней с
			// запаздыванием привода. Выход камер на режим (frac) действует
			// поверх: это разные вещи — раскрутка турбонасосов и
			// отработка уставки.
			command := want * frac
			lag := 1 - math.Exp(-ignitionPredictStep/throttleFilterTime)
			applied += (command - applied) * lag
			thrustAcc = applied

			flow := thrustAcc * mass / (stage.VacuumISP * physics.G0)
			fuel -= flow * ignitionPredictStep
			if fuel < 0 {
				fuel = 0
			}
			out.FuelUsed += flow * ignitionPredictStep
		}

		// Тяга и сопротивление — против вектора скорости, тяжесть — вниз.
		brake := thrustAcc + dragAcc
		if decel := brake - g*vz/v; decel > out.PeakDecel {
			out.PeakDecel = decel
		}
		travel += vh * ignitionPredictStep

		// Нормаль к скорости в плоскости траектории, направленная вверх:
		// (vz, vh)/v при скорости (vh, −vz). Нос на пассивном участке
		// отклонён к зениту, значит подъёмная сила идёт против этой нормали
		// — к земле (см. openLoopBodyAxis).
		vz += (g - brake*vz/v + liftAcc*vh/v) * ignitionPredictStep
		vh += (-brake*vh/v - liftAcc*vz/v) * ignitionPredictStep
		if vh < 0 {
			vh = 0
		}
		alt -= vz * ignitionPredictStep

		if vz <= 0 {
			if !burning {
				// Ещё поднимаемся — прогноз о посадке бессмыслен.
				return out
			}
			// Снижение погашено, а земли нет: розжиг был слишком ранним.
			out.Ran = true
			out.Stalled = true
			out.Touchdown = 0
			return out
		}
	}
	return out
}

// landingBurnIgnitionAltitudePredicted ищет САМУЮ ПОЗДНЮЮ высоту розжига,
// при которой прогноз (см. predictLanding) ещё даёт мягкое касание.
// Устройство самого поиска — в комментарии к лестнице внутри.
// ignitionRecomputeInterval — как часто пересчитывается прогнозная высота
// розжига, с модельного времени.
//
// Прогноз стоит дорого: деление пополам это десяток полных прогонов до
// касания. Считать его на каждом такте (двадцать раз в секунду) незачем —
// высота розжига меняется медленно и непрерывно, а между пересчётами
// достаточно сравнивать с ней текущую высоту. Секунда — тот же порядок, что
// и период пересчёта самой траектории посадки (gfoldResolveInterval).
const ignitionRecomputeInterval = 1.0

// ignitionRecomputeDrop — наибольшая потеря высоты между пересчётами, м.
// Двадцать пять метров — доля длины корпуса: меньше этого решение о розжиге
// всё равно не уточняется, а прогноз стоит дорого.
const ignitionRecomputeDrop = 25.0

// ignitionRecomputeMin — нижний предел периода пересчёта, с. Чаще, чем
// работает сам контур наведения, пересчитывать бессмысленно.
const ignitionRecomputeMin = 0.05

// landingBurnIgnitionAltitude возвращает прогнозную высоту розжига, пересчитывая
// её не чаще ignitionRecomputeInterval.
func (b *Booster) landingBurnIgnitionAltitude(nav orbit.NavState) (altitude float64, feasible bool) {
	if b.ignitionAltValid && b.elapsed-b.ignitionAltAt < b.ignitionRecomputePeriod(nav) {
		return b.ignitionAltCached, b.ignitionFeasible
	}
	b.ignitionAltCached, b.ignitionFeasible = b.landingBurnIgnitionAltitudePredicted(nav)
	b.ignitionAltAt = b.elapsed
	b.ignitionAltValid = true
	return b.ignitionAltCached, b.ignitionFeasible
}

// ignitionRecomputePeriod — через сколько секунд пересчитывать прогнозную
// высоту розжига, с.
//
// Период задан не временем, а ВЫСОТОЙ: между пересчётами ступень не должна
// проходить больше ignitionRecomputeDrop метров. Постоянная секунда была
// рассчитана на подход в двести метров в секунду — там это двести метров
// высоты, мелочь против высоты розжига в два километра. На честной
// аэродинамике ступень подходит вчетверо быстрее, и та же секунда означает
// уже полкилометра: решение о розжиге принималось по высоте, которую
// ступень успевала проскочить раньше, чем проверка срабатывала. Замерено:
// поиск возвращал триста метров, а импульс начинался на ста двадцати.
func (b *Booster) ignitionRecomputePeriod(nav orbit.NavState) float64 {
	vz, _ := descentComponents(nav)
	if vz <= 0 {
		return ignitionRecomputeInterval
	}
	return physics.Clamp(ignitionRecomputeDrop/vz, ignitionRecomputeMin, ignitionRecomputeInterval)
}

// Второе возвращаемое значение — достижима ли вообще мягкая посадка: если
// ни одна высота розжига не даёт её, посадку пора не уточнять, а отменять
// (см. updateLandingAbort).
func (b *Booster) landingBurnIgnitionAltitudePredicted(nav orbit.NavState) (float64, bool) {
	// Пока ступень не снижается, о розжиге говорить нечего.
	if vz, _ := descentComponents(nav); vz <= 0 {
		return 0, true
	}

	// Признак, по которому идёт поиск, — «ОПОЗДАЛИ»: прогноз дошёл до земли
	// и пришёл туда быстрее допустимого. Он монотонен по высоте розжига
	// (ниже зажёг — жёстче касание), и только на нём деление пополам законно.
	//
	// Все прочие исходы прогноза означают не «поздно», а «рано», и потому
	// считаются приемлемыми:
	//
	//   - Stalled — снижение погашено раньше земли: перерасход, не удар;
	//   - Dry     — топливо кончилось за десятки километров до земли:
	//               это признак СЛИШКОМ РАННЕГО розжига, а не позднего;
	//   - !Ran    — прогноз не пришёл ни к чему за отведённое ему время:
	//               до земли ещё далеко, значит и до розжига тоже.
	//
	// Смешение этих случаев обходится дорого. Пока Dry читался как «жёсткое
	// касание», немедленный розжиг на восьмидесяти шести километрах —
	// сжигающий весь остаток за двести секунд в тридцати километрах над
	// водой — выглядел для поиска как «зажигать уже поздно», и поиск честно
	// зажигал.
	aoaCoast := b.coastAngleOfAttack(nav)
	align := b.ignitionAlignDelay(nav)
	// Признак «не годится» в двух строгостях.
	//
	// Строгая (stallOK=false) отвергает и жёсткое касание, и ЗАВИСАНИЕ:
	// погасить снижение в воздухе — не мягкая посадка, а повод падать
	// второй раз. Пока зависание считалось приемлемым, поиск честно
	// выбирал высоту, с которой ступень тормозила до нуля на шестистах
	// метрах и оттуда сваливалась к воде на тридцати м/с, не израсходовав
	// двухсот семидесяти тонн топлива.
	//
	// Мягкая (stallOK=true) — запасная: если строгого решения на лестнице
	// не нашлось (полоса допустимых высот у́же шага лестницы), лучше взять
	// самое низкое зависание, чем объявить посадку недостижимой.
	reject := func(h float64, stallOK bool) bool {
		p := b.predictLanding(nav, h, aoaCoast, align)
		if !p.Ran {
			// Прогноз не дошёл ни до чего за отведённые шаги: до земли ещё
			// далеко, значит и до розжига тоже — «рано», не «поздно».
			return false
		}
		if !p.Reached && h < nav.Altitude {
			// Высота розжига НИЖЕ текущей, но импульс так и не начался:
			// на разворот двигателями вперёд уходит больше, чем осталось
			// падать. Такая ступенька не «слишком ранняя» — она
			// неисполнимая, и принимать её нельзя.
			//
			// Пока она принималась, поиск объявлял достижимой посадку,
			// которой нет: замерено — на пустых баках возвращалась годная
			// высота розжига, расход выходил нулевым, и увод не объявлялся
			// вовсе.
			return true
		}
		if !p.Reached {
			return false
		}
		if p.Dry {
			// Посадка, сжигающая баки досуха, посадкой не является — это
			// отказ при любой высоте розжига.
			//
			// Прежде Dry считался признаком «зажгли рано» и отказом НЕ
			// был. При остатке топлива это верно, при нулевом — нет:
			// сухими оказываются все высоты сразу, поиск берёт самую
			// нижнюю ступеньку и объявляет посадку достижимой. Измерено:
			// на пустых баках возвращался розжиг на девятнадцати метрах с
			// признаком «достижимо», и увод не объявлялся.
			return true
		}
		if p.Stalled {
			return !stallOK
		}
		if p.Touchdown > landingTouchdownSpeed*ignitionSoftFactor {
			return true
		}

		// Запас по тяге на розжиге НЕ требуется, и это проверено.
		//
		// Соблазн понятен: лестница берёт самую нижнюю годную ступеньку, а
		// это ровно та, где потребная тяга почти равна располагаемой.
		// Требование оставить четверть тяги в запасе было опробовано и
		// отвергнуто замером: посадочный импульс тяжёлой ступени — это по
		// своей природе торможение на упоре, и доля потребной тяги падает
		// ниже трёх четвертей только километрах на двенадцати-четырнадцати,
		// где импульс становится вдвое дороже по топливу. Два требования
		// вместе не оставляли годных высот вовсе, поиск проваливался в
		// запасной выход и зажигал на тридцати километрах.
		//
		// Запас, который здесь действительно нужен, — топливный: см. ниже.

		// Запас по топливу — ПРОПОРЦИОНАЛЬНЫЙ расходу самого импульса, тот
		// же, которым план оценивает обеспеченность курса на башню
		// (landingPlanFuelMargin). Одна мера на оба места: иначе лестница
		// отвергает высоту, которую план считает обеспеченной, и наоборот.
		//
		// Прежде здесь вычитался boosterFuelReserveFraction·FuelReserve —
		// доля бюджета РАЗВОРОТНОГО импульса, та самая, которой разворот не
		// имеет права касаться. На посадочном участке разворот уже позади, и
		// то, что от бюджета осталось, и ЕСТЬ посадочный бюджет: вычитать
		// из него разворотный пол значит считать его дважды.
		//
		// Замерено, чего это стоило. На 81.6 км при остатке 182.3 т розжиг
		// на 3.4 км давал касание 3.0 м/с и расход 89.3 т — высота годная.
		// Она отвергалась, потому что 182.3 − 97.5 = 84.8 < 89.3: не хватало
		// четырёх с половиной тонн. Отвергались при этом ВСЕ высоты сразу,
		// а «ни одна не годится» читается как «мягкое касание недостижимо»
		// и даёт необратимый увод. Половина зёрен приходила к воде с
		// восемьюдесятью тоннами в баках, ни разу не включив посадочный
		// импульс.
		return p.FuelUsed*landingPlanFuelMargin > b.propulsion.PropellantMass()
	}

	top := nav.Altitude
	if top <= ignitionSearchFloor {
		return top, !reject(top, true)
	}

	// Поиск — лестница снизу вверх, а НЕ деление пополам.
	//
	// Деление пополам требует монотонности: «выше зажёг — мягче сел». Она
	// держалась, пока прогноз считал разворот бесплатным. Как только на
	// разворот отведено время, монотонность исчезает, и достижимость
	// становится ИНТЕРВАЛОМ: зажечь слишком низко — не хватит высоты на
	// торможение; зажечь слишком высоко — корпус разворачивается
	// двигателями вперёд на километровой скорости и теряет всё
	// аэродинамическое торможение, которым иначе гасил бы её даром
	// (площадь бортом — 900 м² против 114 м² у торца). Деление пополам на
	// таком признаке честно сходилось к ВЕРХНЕЙ границе интервала —
	// двадцать два километра и шесть g торможения там, где хватало
	// нескольких километров.
	//
	// Лестница идёт снизу и берёт ПЕРВУЮ подходящую высоту — то есть самый
	// поздний из физически допустимых розжигов, как и требуется.
	step := math.Pow(top/ignitionSearchFloor, 1/float64(ignitionSearchSteps))

	climb := func(stallOK bool) (float64, bool) {
		prev := 0.0
		for h := ignitionSearchFloor; ; h *= step {
			if h > top {
				h = top
			}
			if !reject(h, stallOK) {
				if prev <= 0 {
					// Годится первая же ступенька — уточнять ниже нечего.
					//
					// Раньше уточнение шло от нуля, и деление пополам
					// возвращало высоту НИЖЕ ignitionSearchFloor: прогноз
					// с такой высоты не успевает взвестись (на разворот
					// двигателями вперёд уходит больше, чем остаётся), в
					// reject это читается как «слишком рано» и принимается.
					// Замерено на быстром входе: поиск возвращал 19 метров,
					// то есть посадочный импульс не начинался вовсе.
					return h, true
				}
				// Уточнение между последней негодной ступенькой и этой.
				lo, hi := prev, h
				for i := 0; i < ignitionRefineSteps; i++ {
					mid := (lo + hi) / 2
					if reject(mid, stallOK) {
						lo = mid
					} else {
						hi = mid
					}
				}
				return hi, true
			}
			prev = h
			if h >= top {
				return top, false
			}
		}
	}

	if h, ok := climb(false); ok {
		return h, true
	}

	if h, ok := climb(true); ok {
		return h, true
	}

	// Ни одна высота не даёт мягкого касания. Зажигать всё равно надо —
	// тормозить чем есть лучше, чем не тормозить, — но это же состояние и
	// есть повод для увода (см. landingAbortReason).
	return top, false
}

// ignitionSoftFactor — во сколько раз прогнозируемая скорость касания может
// превышать целевую и всё ещё считаться мягкой посадкой при поиске высоты
// розжига.
//
// Запас нужен потому, что прогноз огрублён (полусекундный шаг, только
// вертикальный канал, ориентация взята постоянной): требовать от него
// попадания в саму целевую скорость значило бы принимать решение по
// точности, которой у него нет. Тройка — тот масштаб, на котором грубость
// прогноза уже не решает, а запас ещё не съедает поздний розжиг.
const ignitionSoftFactor = 3.0
