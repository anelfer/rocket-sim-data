// Package gfold — наведение посадочного импульса по методу G-FOLD
// (Guidance for Fuel-Optimal Large Divert), разработанному в Лаборатории
// реактивного движения НАСА (Açıkmeşe, Ploen, Blackmore, Scharf).
//
// # Чем это отличается от расписания торможения
//
// Прежнее наведение посадочного импульса решало две задачи по отдельности:
// вертикальный канал вёл скорость снижения по профилю v(h)=√(v_т²+2·a·h),
// горизонтальный — гасил снос к нулю за оценённое время до касания. Такое
// наведение по построению не умеет ЦЕЛИТЬСЯ: у него нет ни понятия «точка
// посадки», ни способа распорядиться оставшимся топливом так, чтобы попасть
// в неё. Отсюда и результат — приводнение мягкое, но за десятки километров
// от площадки, с четвертью заправки, так и не потраченной ни на что.
//
// G-FOLD ставит задачу целиком и решает её как ЗАДАЧУ ОПТИМИЗАЦИИ:
//
//	минимизировать расход топлива
//	при условии    прийти в заданную точку с заданной скоростью,
//	               не выходя за пределы тяги, угла отклонения тяги
//	               и посадочного конуса.
//
// Ключевая идея метода (и причина, по которой он вообще применим на борту):
// исходная задача НЕ выпукла — ровно из-за нижней границы тяги ‖T‖ ≥ ρ₁ > 0
// (работающий двигатель нельзя задросселировать до нуля, поэтому допустимое
// множество тяг — сферический слой, а не шар). Замена переменных
//
//	u = T/m,   σ = Γ/m,   z = ln m
//
// вместе с введением расщепляющей переменной Γ ≥ ‖T‖ превращает её в
// выпуклую задачу конического программирования второго порядка, причём
// БЕЗ ПОТЕРИ ТОЧНОСТИ: теорема о lossless convexification утверждает, что в
// любом оптимуме релаксированной задачи выполняется ‖u‖ = σ, то есть
// найденное решение — решение исходной задачи, а не её приближение. Это не
// эвристика и не «достаточно близко»: оптимум тот же самый.
//
// # Что здесь реализовано
//
//   - Постановка (problem.go): дискретизация с линейным восполнением (FOH),
//     состояния исключены и выражены аффинно через управления, так что
//     переменными остаются только (u₀..u_N, σ₀..σ_N).
//   - Обезразмеривание (discretize.go): без него задача плохо обусловлена —
//     положение порядка 10⁴ м, масса 10⁵ кг, α порядка 10⁻⁴.
//   - Приоритет задач (solve.go): сначала пробуется точное попадание в цель
//     с минимумом топлива; если оно физически недостижимо — задача
//     минимального промаха (Problem 3 по Blackmore и др.), а затем минимум
//     топлива при уже достигнутом промахе (Problem 4). Промах при этом —
//     честно посчитанная физическая величина, а не молчаливый отказ.
//   - Свободное время полёта (solve.go): золотое сечение по числу узлов при
//     ФИКСИРОВАННОМ шаге сетки.
//
// Решатель конической задачи — simulator/orbit/socp, тоже собственный:
// внешних зависимостей у проекта нет.
package gfold

import (
	"math"

	"rocketTelemetrySim/simulator/physics"
)

// Vehicle — паспортные и текущие данные ступени для постановки задачи.
// Всё, кроме массы, — либо конструктивные константы, либо то, что борт
// знает про сам себя (сколько камер зажжено, каков нижний предел
// дросселирования): измерять эти величины не нужно и нечем.
type Vehicle struct {
	// WetMass — масса на момент решения, кг. Приходит из внутреннего учёта
	// борта (заправка минус проинтегрированный расход), а не с датчика —
	// как и у корабля (см. Simulation.sensedNavState).
	WetMass float64

	// DryMass — нижняя допустимая масса, кг. Не сухая масса конструкции как
	// таковая, а сухая масса ПЛЮС резерв, который наведение не имеет права
	// планировать к расходу.
	DryMass float64

	// Alpha — расход массы на единицу тяги, 1/(Isp·g₀), с/м.
	Alpha float64

	// Rho1, Rho2 — нижняя и верхняя границы модуля тяги по узлам сетки, Н.
	// Поузловые, а не скалярные: тяга камеры зависит от高ты (сопло работает
	// против внешнего давления), и на посадочном импульсе аппарат проходит
	// весь диапазон от разрежённых слоёв до уровня моря.
	Rho1, Rho2 []float64

	// ThetaMax — предельный угол отклонения вектора тяги от опорного
	// направления PointAxis, рад.
	ThetaMax float64

	// PointAxis — опорное направление для ограничения на угол тяги, в осях
	// посадочной системы (обычно вертикаль (0,0,1)).
	PointAxis physics.Vec3

	// GlideSlope — угол посадочного конуса над горизонтом, рад. Ноль
	// отключает ограничение.
	GlideSlope float64

	// GlideSkipNodes — сколько первых узлов освобождается от конуса.
	// Положение в узле 0 задано начальным условием и ничем не управляется:
	// если аппарат сейчас вне конуса (а при возврате издалека это норма),
	// требование конуса в нулевом узле сделало бы задачу неразрешимой
	// безо всякой физической причины.
	GlideSkipNodes int

	// GlideApexDepth — насколько ниже точки посадки опущена вершина конуса,
	// м. У самой вершины конус вырождается в точку, и терминальный узел
	// оказывался бы ровно в его особенности.
	GlideApexDepth float64
}

// State — начальное состояние в посадочной системе координат.
type State struct {
	Position, Velocity physics.Vec3
}

// Setup — полная постановка ОДНОГО решения: сетка задана, время полёта
// фиксировано (перебор по нему — снаружи, см. SolveFreeTime).
type Setup struct {
	Vehicle
	State

	// Gravity — ускорение свободного падения в осях посадочной системы,
	// м/с². Постоянно на всём импульсе: посадочный участок — единицы
	// километров, изменение g на них порядка 0.003 м/с².
	Gravity physics.Vec3

	// Bias — известное поузловое ускорение, НЕ зависящее от управления,
	// м/с²: аэродинамическое сопротивление, силы Кориолиса и центробежная
	// (посадочная система связана с вращающейся Землёй), поправка на
	// изменение силы тяжести с высотой. nil означает «только Gravity».
	//
	// Всё это входит в задачу как ИЗВЕСТНОЕ слагаемое правой части, а не
	// как функция состояния: сопротивление квадратично по скорости, сила
	// Кориолиса линейна по ней — стоит записать их через переменные
	// задачи, и динамика перестанет быть линейной, а вместе с ней
	// потеряется вся выпуклость, ради которой метод и существует.
	// Поэтому они замораживаются по ПРЕДЫДУЩЕЙ найденной траектории и
	// уточняются повторным решением (итерация Пикара): поправки малы по
	// сравнению с самой тягой, и двух проходов хватает.
	Bias []physics.Vec3

	// TargetPosition — точка касания в осях посадочной системы, м. Обычно
	// начало координат (система строится от площадки), но задаётся явно:
	// цель может быть смещена, и молчаливое предположение «цель в нуле»
	// было бы именно тем допущением, которое потом ищут по всему коду.
	TargetPosition physics.Vec3

	// TargetVelocity — требуемая скорость в момент касания, м/с.
	TargetVelocity physics.Vec3

	// Nodes — число ИНТЕРВАЛОВ сетки N (узлов N+1).
	Nodes int

	// Step — шаг сетки Δt, с. Время полёта равно Nodes·Step.
	Step float64

	// MissTolerance — допустимый промах для задачи «минимум топлива при
	// ограниченном промахе», м.
	MissTolerance float64

	// Objective — что именно минимизировать. См. Objective.
	Objective Objective
}

// TimeOfFlight возвращает время полёта постановки, с.
func (s Setup) TimeOfFlight() float64 { return float64(s.Nodes) * s.Step }

// Objective — постановка задачи: что минимизируется и насколько жёстко
// задана точка касания.
//
// Различать их приходится не из любви к общности. Приоритетная схема
// Blackmore—Açıkmeşe—Scharf (сначала минимум промаха, потом минимум топлива
// при этом промахе) написана для случая, когда площадка ДОСТИЖИМА и вопрос
// лишь в том, насколько точно и насколько дёшево в неё попасть. Если же она
// недостижима, та же схема в замкнутом контуре ведёт себя разрушительно:
// на каждом пересчёте выгоднее потратить топливо на сокращение промаха
// СЕЙЧАС, а посадку оставить на потом, — и поскольку «потом» наступает уже
// с новым пересчётом, который рассуждает так же, посадочный остаток
// проедается целиком, ни разу не будучи израсходованным по назначению.
// Измерено на живом прогоне: промах сокращался с 54.6 до 50.1 км, после
// чего топливо кончалось на восьми километрах высоты и ступень падала со
// скоростью около двухсот метров в секунду.
//
// Поэтому в замкнутом контуре применяются только две крайние постановки:
// точное попадание, пока оно достижимо, и мягкая посадка со свободной
// точкой касания, когда нет. Минимум промаха остаётся — он честно отвечает
// на вопрос «насколько близко вообще можно сесть» — но как разовая оценка,
// а не как закон наведения.
type Objective int

const (
	// ObjectiveMinimumMiss — приоритетная схема статьи: сначала минимум
	// горизонтального промаха, затем минимум топлива при найденном
	// промахе. Значение по умолчанию.
	ObjectiveMinimumMiss Objective = iota

	// ObjectiveReachTarget — минимум топлива при ТОЧНОМ попадании в цель.
	// Неразрешима, если цель недостижима, — и это ответ, а не отказ.
	ObjectiveReachTarget

	// ObjectiveSoftLanding — минимум топлива при СВОБОДНОЙ горизонтальной
	// точке касания: сесть мягко там, где дешевле всего. Горизонтальная
	// цель не задаётся вовсе, промах считается по факту.
	ObjectiveSoftLanding
)

// Status — исход решения задачи наведения.
type Status int

const (
	// StatusOptimal — решение найдено.
	StatusOptimal Status = iota

	// StatusInfeasible — при этом времени полёта задача не имеет решения:
	// физически невозможно прийти в цель с заданной скоростью, не выходя
	// за пределы тяги и конуса.
	StatusInfeasible

	// StatusFailed — решатель не сошёлся или потерял точность. НЕ то же
	// самое, что StatusInfeasible: там ответ «нельзя», здесь «не знаем».
	// Наведение обязано различать их — в первом случае надо менять
	// постановку, во втором лететь по предыдущему решению.
	StatusFailed
)

// String возвращает название исхода.
func (s Status) String() string {
	switch s {
	case StatusOptimal:
		return "optimal"
	case StatusInfeasible:
		return "infeasible"
	case StatusFailed:
		return "failed"
	default:
		return "?"
	}
}

// Trajectory — найденная опорная траектория и управление на ней.
type Trajectory struct {
	Status Status

	// Step, Nodes — сетка, на которой посчитано решение.
	Step  float64
	Nodes int

	// Accel — оптимальное ускорение от тяги u_k = T_k/m_k в узлах, м/с².
	// Именно ускорение, а не тяга: тяга зависит от массы, а масса на
	// исполнении отличается от запланированной, и умножать надо на
	// ФАКТИЧЕСКУЮ (см. Command).
	Accel []physics.Vec3

	// Sigma — расщепляющая переменная σ_k, м/с². В точном решении
	// σ_k = ‖u_k‖ (теорема о lossless convexification); расхождение
	// измеряется полем Slack.
	Sigma []float64

	// Position, Velocity, Mass — опорная траектория в узлах.
	Position, Velocity []physics.Vec3
	Mass               []float64

	// Miss — горизонтальный промах терминального узла относительно цели, м.
	Miss float64

	// FuelUsed — запланированный расход топлива, кг.
	FuelUsed float64

	// Slack — максимальная по узлам относительная невязка условия ‖u‖=σ.
	// Величина, по которой видно, работает ли теорема о lossless
	// convexification на этой конкретной задаче: значимо ненулевой slack
	// означает, что какое-то из добавленных ограничений вышло за рамки
	// доказанного, и решение больше не обязано быть оптимальным для
	// исходной невыпуклой задачи. Публикуется в телеметрии, а не
	// проверяется молча.
	Slack float64

	// Iterations — сколько итераций метода внутренней точки потребовалось.
	Iterations int
}

// TimeOfFlight возвращает время полёта траектории, с.
func (t *Trajectory) TimeOfFlight() float64 { return float64(t.Nodes) * t.Step }

// Command возвращает опорное ускорение, положение и скорость в момент
// времени since (секунд от начала траектории) линейным восполнением между
// узлами — тем же самым, на котором траектория и решалась (FOH), так что
// это не приближение решения, а само решение в промежуточной точке.
//
// За пределами траектории возвращаются значения крайних узлов: наведение,
// пережившее собственное расчётное время полёта, обязано продолжать
// выдавать осмысленную команду, а не обрываться.
func (t *Trajectory) Command(since float64) (accel, position, velocity physics.Vec3) {
	if len(t.Accel) == 0 {
		return physics.Vec3{}, physics.Vec3{}, physics.Vec3{}
	}
	if since <= 0 {
		return t.Accel[0], t.Position[0], t.Velocity[0]
	}
	last := len(t.Accel) - 1
	idx := int(since / t.Step)
	if idx >= last {
		return t.Accel[last], t.Position[last], t.Velocity[last]
	}
	frac := since/t.Step - float64(idx)
	lerp := func(a, b physics.Vec3) physics.Vec3 {
		return a.Add(b.Sub(a).Scale(frac))
	}
	return lerp(t.Accel[idx], t.Accel[idx+1]),
		lerp(t.Position[idx], t.Position[idx+1]),
		lerp(t.Velocity[idx], t.Velocity[idx+1])
}

// MassAt возвращает запланированную массу в момент since, кг.
func (t *Trajectory) MassAt(since float64) float64 {
	if len(t.Mass) == 0 {
		return 0
	}
	last := len(t.Mass) - 1
	if since <= 0 {
		return t.Mass[0]
	}
	idx := int(since / t.Step)
	if idx >= last {
		return t.Mass[last]
	}
	frac := since/t.Step - float64(idx)
	return t.Mass[idx] + (t.Mass[idx+1]-t.Mass[idx])*frac
}

// ConstantBounds раскладывает скалярные границы тяги по всем узлам —
// вспомогательная функция для случая, когда зависимостью тяги от высоты
// на этом участке можно пренебречь.
func ConstantBounds(rho1, rho2 float64, nodes int) (lo, hi []float64) {
	lo = make([]float64, nodes+1)
	hi = make([]float64, nodes+1)
	for i := range lo {
		lo[i], hi[i] = rho1, rho2
	}
	return lo, hi
}

// MaxTimeOfFlight — верхняя граница времени полёта, с: даже на самом низком
// допустимом расходе (нижняя граница тяги ρ₁) топливо кончается за это
// время. Точная, а не оценочная: расход не может быть меньше α·ρ₁.
func MaxTimeOfFlight(v Vehicle) float64 {
	if len(v.Rho1) == 0 || v.Alpha <= 0 {
		return 0
	}
	rho1 := v.Rho1[0]
	for _, r := range v.Rho1 {
		if r < rho1 {
			rho1 = r
		}
	}
	if rho1 <= 0 {
		return 0
	}
	return (v.WetMass - v.DryMass) / (v.Alpha * rho1)
}

// MinTimeOfFlight — нижняя граница времени полёта, с: за меньшее время
// невозможно изменить скорость от v₀ до v_f даже на полной тяге и при
// минимальной массе.
//
// Учитывает гравитацию, а не только модуль потребного приращения скорости:
// требуется ‖v_f − v₀ − g·t‖ ≤ (ρ₂/m_сух)·t, что после возведения в квадрат
// даёт квадратное неравенство a·t² + b·t + c ≥ 0. Оценка без гравитации
// (t = m‖v₀‖/ρ₂) слабее, а разница здесь не косметическая: на посадочном
// импульсе вектор g направлен туда же, куда и гасимая скорость.
//
// Возвращает ok=false, если располагаемого ускорения не хватает даже на то,
// чтобы удержать вес (a ≤ 0) — тогда никакое время полёта не годится.
func MinTimeOfFlight(v Vehicle, from, to physics.Vec3, gravity physics.Vec3) (float64, bool) {
	if v.DryMass <= 0 || len(v.Rho2) == 0 {
		return 0, false
	}
	rho2 := v.Rho2[0]
	for _, r := range v.Rho2 {
		if r > rho2 {
			rho2 = r
		}
	}
	dv := to.Sub(from)
	amax := rho2 / v.DryMass
	a := amax*amax - gravity.Dot(gravity)
	if a <= 0 {
		return 0, false
	}
	b := -2 * gravity.Dot(dv)
	c := -dv.Dot(dv)
	disc := b*b - 4*a*c
	if disc < 0 {
		return 0, false
	}
	t := (-b + math.Sqrt(disc)) / (2 * a)
	if t < 0 || math.IsNaN(t) {
		return 0, false
	}
	return t, true
}
