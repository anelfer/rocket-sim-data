package gfold

import (
	"math"

	"rocketTelemetrySim/simulator/physics"
)

// -----------------------------------------------------------------------------
// Дискретизация задачи и обезразмеривание.
//
// Управление восполняется между узлами ЛИНЕЙНО (first-order hold, FOH), а не
// ступенькой (zero-order hold). Причин три, и все три существенные:
//
//  1. Условие ‖u‖ ≤ σ, наложенное в узлах, при линейном восполнении
//     выполняется и МЕЖДУ узлами автоматически — просто по выпуклости нормы:
//     ‖(1−θ)u_k + θu_{k+1}‖ ≤ (1−θ)‖u_k‖ + θ‖u_{k+1}‖ ≤ (1−θ)σ_k + θσ_{k+1}.
//     Со ступенькой это тоже верно, но ступенька даёт куда более грубое
//     управление при том же числе узлов.
//  2. Второй порядок точности вместо первого: оптимальное решение задачи
//     мягкой посадки — гладко поворачивающийся вектор тяги, и кусочно
//     постоянное ускорение приближает его заметно хуже.
//  3. Команда, которую наведение отдаёт автопилоту, оказывается непрерывной.
//     Ступенчатая команда means скачок направления тяги на каждом узле —
//     корпус массой в сотни тонн за такой командой физически не успевает, и
//     ошибка слежения возвращается в контур как возмущение.
//
// Состояния (положение, скорость, логарифм массы) в число переменных НЕ
// входят: они выражены аффинно через управления и подставлены в ограничения.
// Это не оптимизация ради скорости, а условие применимости выбранного
// решателя: при исключённых состояниях задача остаётся размера 4(N+1)
// (сотни переменных), а с ними выросла бы втрое и потребовала бы разреженной
// факторизации общего вида.
// -----------------------------------------------------------------------------

// weights — таблицы аффинных коэффициентов дискретизации.
//
// vel[k][i] — вклад управления в узле i в СКОРОСТЬ в узле k (правило
// трапеций); pos[k][i] — то же для ПОЛОЖЕНИЯ.
type weights struct {
	vel [][]float64
	pos [][]float64
}

// newWeights строит таблицы для сетки из nodes интервалов.
//
// Формулы (вывод — интегрирование линейно восполненного управления):
//
//	v_k = v₀ + Δt·Σᵢ wᵛ_{k,i}·(u_i + b_i)
//	r_k = r₀ + k·Δt·v₀ + Δt²·Σᵢ wʳ_{k,i}·(u_i + b_i)
//
//	wᵛ_{k,i} = ½ при i∈{0,k}; 1 при 0<i<k; 0 при i>k
//	wʳ_{k,i} = ⅓+(k−1)/2 при i=0; k−i при 1≤i≤k−1; ⅙ при i=k; 0 при i>k
//
// Проверяются тождествами Σᵢ wᵛ_{k,i} = k и Σᵢ wʳ_{k,i} = k²/2 (см. тест):
// при постоянном управлении они обязаны воспроизводить равноускоренное
// движение точно, и любая ошибка на единицу в индексах их немедленно ломает.
func newWeights(nodes int) weights {
	w := weights{
		vel: make([][]float64, nodes+1),
		pos: make([][]float64, nodes+1),
	}
	for k := 0; k <= nodes; k++ {
		w.vel[k] = make([]float64, nodes+1)
		w.pos[k] = make([]float64, nodes+1)
		if k == 0 {
			continue
		}
		for i := 0; i <= k; i++ {
			switch {
			case i == 0:
				w.vel[k][i] = 0.5
				w.pos[k][i] = 1.0/3.0 + float64(k-1)/2
			case i == k:
				w.vel[k][i] = 0.5
				w.pos[k][i] = 1.0 / 6.0
			default:
				w.vel[k][i] = 1
				w.pos[k][i] = float64(k - i)
			}
		}
	}
	return w
}

// scales — множители обезразмеривания.
//
// В единицах СИ задача плохо обусловлена: положение порядка 10⁴ м, скорость
// 10², масса 10⁵ кг, логарифм массы около 12.6, а сама интересующая
// величина δ = z − z₀ — около 0.05. Считать δ вычитанием двух чисел
// величиной 12.6 значит потерять на этом полтора десятичных знака ещё до
// того, как ограничение попадёт в решатель. После обезразмеривания все
// величины задачи имеют порядок единицы.
type scales struct {
	length float64 // L
	time   float64 // T = √(L/g)
	mass   float64 // M
	accel  float64 // L/T² — по построению равно g
}

// newScales выбирает масштабы по самой задаче: характерная длина — расстояние
// до цели (не константа: к концу импульса оно падает на порядки, и
// фиксированный масштаб снова расстроил бы обусловленность), характерное
// время — время свободного падения с этой высоты.
func newScales(s Setup) scales {
	g := s.Gravity.Norm()
	if g <= 0 {
		g = physics.G0
	}
	l := s.Position.Norm()
	// Нижний предел не «на всякий случай»: у самой площадки расстояние до
	// цели обращается в ноль, и масштаб длины вместе с ним. Метр — величина
	// порядка точности, которой задача всё равно оперирует.
	if l < 1 {
		l = 1
	}
	t := math.Sqrt(l / g)
	m := s.WetMass
	if m <= 0 {
		m = 1
	}
	return scales{length: l, time: t, mass: m, accel: l / (t * t)}
}

// massProfile возвращает поузловой логарифм МИНИМАЛЬНО возможной массы
// (обезразмеренный, z̃ = ln(m/M)) — опорную точку, вокруг которой
// линеаризуются границы тяги.
//
// Минимально возможная масса — та, что осталась бы при расходе на верхней
// границе тяги всё время до этого узла. Это ЗАВЕДОМАЯ нижняя оценка, а не
// прогноз: настоящая масса не может быть меньше, каким бы ни было решение.
// Именно поэтому построенные вокруг неё границы (см. problem.go) остаются
// консервативными — любое решение приближённой задачи допустимо и для
// точной.
//
// Пол по сухой массе обязателен: без него при большом времени полёта
// выражение уходит в ноль и ниже, логарифм — в −∞, и коэффициенты
// ограничений теряют смысл.
func massProfile(s Setup, sc scales) []float64 {
	z := make([]float64, s.Nodes+1)
	mass := s.WetMass
	for k := 0; k <= s.Nodes; k++ {
		if k > 0 {
			rho := (s.Rho2[k-1] + s.Rho2[k]) / 2
			mass -= s.Alpha * s.Step * rho
		}
		if mass < s.DryMass {
			mass = s.DryMass
		}
		z[k] = math.Log(mass / sc.mass)
	}
	return z
}

// affineOffsets возвращает поузловые «свободные члены» траектории — то, где
// оказался бы аппарат, если бы тяга была нулевой, а действовали только
// гравитация и известное сопротивление. Обезразмеренные.
//
//	p_k = r₀ + k·Δt·v₀ + Δt²·Σᵢ wʳ_{k,i}·b_i
//	q_k = v₀ + Δt·Σᵢ wᵛ_{k,i}·b_i,   b_i = g + a_сопр,i
func affineOffsets(s Setup, sc scales, w weights) (pos, vel []physics.Vec3) {
	n := s.Nodes
	dt := s.Step / sc.time
	r0 := s.Position.Scale(1 / sc.length)
	v0 := s.Velocity.Scale(sc.time / sc.length)

	b := make([]physics.Vec3, n+1)
	for i := range b {
		acc := s.Gravity
		if s.Bias != nil && i < len(s.Bias) {
			acc = acc.Add(s.Bias[i])
		}
		b[i] = acc.Scale(1 / sc.accel)
	}

	pos = make([]physics.Vec3, n+1)
	vel = make([]physics.Vec3, n+1)
	for k := 0; k <= n; k++ {
		sumP := physics.Vec3{}
		sumV := physics.Vec3{}
		for i := 0; i <= k; i++ {
			if wp := w.pos[k][i]; wp != 0 {
				sumP = sumP.Add(b[i].Scale(wp))
			}
			if wv := w.vel[k][i]; wv != 0 {
				sumV = sumV.Add(b[i].Scale(wv))
			}
		}
		pos[k] = r0.Add(v0.Scale(float64(k) * dt)).Add(sumP.Scale(dt * dt))
		vel[k] = v0.Add(sumV.Scale(dt))
	}
	return pos, vel
}
