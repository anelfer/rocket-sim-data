package socp

import "math"

// -----------------------------------------------------------------------------
// Линейная система метода внутренней точки (KKT).
//
// На каждой итерации метод решает систему
//
//	⎡ 0   Aᵀ   Gᵀ  ⎤ ⎡dx⎤   ⎡rx⎤
//	⎢ A   0    0   ⎥ ⎢dy⎥ = ⎢ry⎥
//	⎣ G   0  −WᵀW  ⎦ ⎣dz⎦   ⎣rz⎦
//
// Решать её в таком виде (размер n+p+m) значило бы факторизовать матрицу
// втрое большего порядка, чем нужно: третий блок исключается аналитически,
// потому что WᵀW блочно-диагональна и обращается в замкнутом виде (cone.go).
// После исключения остаётся седловая система порядка n+p:
//
//	⎡ GᵀW⁻²G   Aᵀ ⎤ ⎡dx⎤   ⎡ rx + GᵀW⁻²·rz ⎤
//	⎣ A        0  ⎦ ⎣dy⎦ = ⎣ ry            ⎦
//
// Для задачи G-FOLD (N≈24 узла) это порядок около сотни — плотная
// факторизация здесь дешевле любой разреженной схемы с её служебными
// структурами и переупорядочиванием.
//
// Матрица квазиопределённая (положительно определённый блок сверху,
// отрицательно определённый снизу) только ПОСЛЕ регуляризации: без неё
// нижний блок строго нулевой, и LDLᵀ без выбора ведущего элемента на нём
// делится на ноль. Регуляризация +δ/−δ по диагонали делает разложение
// безусловно выполнимым, а внесённое ею возмущение снимается итерационным
// уточнением по ИСХОДНОЙ, нерегуляризованной матрице — приём стандартный
// (так работают и OOQP, и ECOS), и без него точность решения падала бы
// вместе с обусловленностью задачи у самого конца посадки.
// -----------------------------------------------------------------------------

// kktSystem — рабочая память для одной факторизации. Переиспользуется между
// итерациями и между решениями: наведение вызывает решатель каждые несколько
// секунд модельного времени, и выделять под каждую итерацию новые массивы
// значило бы кормить сборщик мусора там, где размер задачи известен заранее.
type kktSystem struct {
	n, p, dim int

	// mat — симметричная матрица dim×dim, заполняется ТОЛЬКО нижний
	// треугольник (i ≥ j). Верхний не хранится и не читается: и разложение
	// (factor), и умножение на вектор (symMulVec) написаны под нижний
	// треугольник, а заполнять обе половины значило бы делать вдвое больше
	// работы в самом горячем месте решателя — сборке нормальной матрицы.
	mat []float64

	// orig — копия mat ДО регуляризации, для итерационного уточнения.
	orig []float64

	// l, d — множители разложения mat = L·D·Lᵀ (L нижняя унитреугольная,
	// хранится в тех же клетках, что и mat).
	l []float64
	d []float64

	// Рабочие векторы итерационного уточнения.
	rhs, sol, res, cor []float64

	// Рабочая память сборки блока конуса второго порядка (см. assemble):
	// накопитель комбинации строк и список затронутых столбцов, чтобы не
	// обходить все n столбцов ради нескольких десятков ненулевых.
	acc      []float64
	accTouch []int
	accSeen  []bool

	// diagRow — строка разложения, умноженная на диагональ D (см. factor).
	diagRow []float64

	// linDiag — диагональ W⁻² линейной части, переиспользуется между
	// итерациями.
	linDiag []float64

	delta float64
}

func newKKT(n, p int) *kktSystem {
	dim := n + p
	return &kktSystem{
		n: n, p: p, dim: dim,
		mat:  make([]float64, dim*dim),
		orig: make([]float64, dim*dim),
		l:    make([]float64, dim*dim),
		d:    make([]float64, dim),
		rhs:  make([]float64, dim),
		sol:  make([]float64, dim),
		res:  make([]float64, dim),
		cor:  make([]float64, dim),

		acc:      make([]float64, n),
		accTouch: make([]int, 0, n),
		accSeen:  make([]bool, n),
		diagRow:  make([]float64, dim),
	}
}

// addOuter прибавляет scale·v·vᵀ к нижнему треугольнику, где v задан
// списком затронутых столбцов (разреженно). Список обязан быть
// упорядоченным по возрастанию — тогда внутренний цикл проходит ровно по
// треугольнику, без проверки на каждой клетке.
func (k *kktSystem) addOuter(cols []int, v []float64, scale float64) {
	dim := k.dim
	for a := 0; a < len(cols); a++ {
		ia := cols[a]
		va := scale * v[ia]
		if va == 0 {
			continue
		}
		row := k.mat[ia*dim:]
		for b := 0; b <= a; b++ {
			ib := cols[b]
			row[ib] += va * v[ib]
		}
	}
}

// addRowOuter прибавляет scale·row·rowᵀ к нижнему треугольнику, где row —
// строка разреженной матрицы. Столбцы внутри строки упорядочены по
// построению (см. SparseBuilder.Build), поэтому внутренний цикл идёт до
// текущего столбца включительно и обходит ровно нижний треугольник.
func (k *kktSystem) addRowOuter(g *Sparse, r int, scale float64) {
	dim := k.dim
	lo, hi := g.RowPtr[r], g.RowPtr[r+1]
	for a := lo; a < hi; a++ {
		ia, va := g.Col[a], scale*g.Val[a]
		if va == 0 {
			continue
		}
		row := k.mat[ia*dim:]
		for b := lo; b <= a; b++ {
			row[g.Col[b]] += va * g.Val[b]
		}
	}
}

// assemble собирает и факторизует матрицу для текущего масштабирования.
// scale=nil означает W=I — этим пользуется поиск начальной точки (solver.go),
// где масштабирования ещё нет.
func (k *kktSystem) assemble(p *Problem, sc *scaling, delta float64) bool {
	dim := k.dim
	for i := range k.mat {
		k.mat[i] = 0
	}

	// Верхний левый блок: GᵀW⁻²G. Считается поблочно по конусам: между
	// блоками W⁻² нулевая, внутри блока — см. ниже.
	var diag []float64
	if sc != nil && p.K.Linear > 0 {
		if cap(k.linDiag) < p.K.Linear {
			k.linDiag = make([]float64, p.K.Linear)
		}
		diag = k.linDiag[:p.K.Linear]
		for i := range diag {
			diag[i] = 1 / (sc.diag[i] * sc.diag[i])
		}
	}

	g := p.G
	if g != nil {
		// Линейная часть: W⁻² диагональна, каждая строка даёт ранг-1 вклад.
		for r := 0; r < p.K.Linear; r++ {
			wr := 1.0
			if diag != nil {
				wr = diag[r]
			}
			k.addRowOuter(g, r, wr)
		}

		// Конусы второго порядка. Наивно это d² произведений строк на
		// строку — и именно здесь решатель проводил бы бо́льшую часть
		// времени: строки ограничений на ПОЛОЖЕНИЕ плотные (положение в
		// узле k зависит от всех управлений до него), так что d²·nnz²
		// доминирует над всем остальным, включая саму факторизацию.
		//
		// Но W⁻² для конуса второго порядка — не произвольная плотная
		// матрица: из стрелочного вида масштабирования Нестерова—Тодда
		// прямой подстановкой получается
		//
		//	W² = η²·(2·w·wᵀ − J),   W⁻² = η⁻²·(2·w̄·w̄ᵀ − J),
		//
		// где w̄ = (w₀, −w₁), J = diag(1, −I). То есть это диагональ плюс
		// матрица ранга один — и вместо d² произведений строк достаточно
		// d+1 внешних произведений: одно для комбинации строк с весами w̄,
		// и по одному на строку для диагональной части. Для блока
		// посадочного конуса (d=3, строки по ~3N ненулей) это вчетверо
		// меньше работы, и ровно во столько же раз быстрее весь решатель.
		coneOff := p.K.Linear
		for bi, d := range p.K.SOC {
			blk := block{coneOff, coneOff + d}
			coneOff += d
			if sc == nil {
				// W = I: W⁻² = I, вклад — просто сумма ранг-1 по строкам.
				for a := 0; a < d; a++ {
					k.addRowOuter(g, blk.lo+a, 1)
				}
				continue
			}
			bw := sc.blockW(bi)

			// v = Σ_a w̄_a·(строка a), накапливается разреженно.
			k.accTouch = k.accTouch[:0]
			for a := 0; a < d; a++ {
				wa := bw[a]
				if a > 0 {
					wa = -wa
				}
				if wa == 0 {
					continue
				}
				r := blk.lo + a
				for ka := g.RowPtr[r]; ka < g.RowPtr[r+1]; ka++ {
					col := g.Col[ka]
					if !k.accSeen[col] {
						k.accSeen[col] = true
						k.accTouch = append(k.accTouch, col)
						k.acc[col] = 0
					}
					k.acc[col] += wa * g.Val[ka]
				}
			}
			sortInts(k.accTouch)
			inv := 1 / (sc.eta[bi] * sc.eta[bi])
			k.addOuter(k.accTouch, k.acc, 2*inv)
			for _, c := range k.accTouch {
				k.accSeen[c] = false
			}

			// Диагональная часть −J: минус для первой строки блока, плюс
			// для остальных (знак J обращён вычитанием).
			for a := 0; a < d; a++ {
				sign := -inv
				if a > 0 {
					sign = inv
				}
				k.addRowOuter(g, blk.lo+a, sign)
			}
		}
	}

	// Блок A (строки равенств идут после переменных, поэтому попадают
	// именно в нижний треугольник — транспонированную половину хранить не
	// нужно, см. комментарий у поля mat).
	if p.A != nil {
		for r := 0; r < p.A.Rows; r++ {
			row := k.n + r
			for a := p.A.RowPtr[r]; a < p.A.RowPtr[r+1]; a++ {
				k.mat[row*dim+p.A.Col[a]] += p.A.Val[a]
			}
		}
	}

	copy(k.orig, k.mat)

	// Регуляризация: +δ сверху, −δ снизу.
	for i := 0; i < k.n; i++ {
		k.mat[i*dim+i] += delta
	}
	for i := k.n; i < dim; i++ {
		k.mat[i*dim+i] -= delta
	}
	k.delta = delta

	return k.factor()
}

// factor выполняет разложение LDLᵀ без выбора ведущего элемента.
//
// Без выбора — потому что после регуляризации матрица квазиопределённая:
// у такой матрицы разложение существует при ЛЮБОЙ перестановке, то есть
// выбирать нечего (теорема Вандербея о квазиопределённых матрицах). Именно
// ради этого свойства регуляризация и введена: перестановки строк в
// седловой системе разрушили бы блочную структуру, ради которой всё
// исключение и затевалось.
func (k *kktSystem) factor() bool {
	dim := k.dim
	l, d, m := k.l, k.d, k.mat
	for i := range l {
		l[i] = 0
	}

	// dl — строка j, умноженная поэлементно на D: выносится из внутреннего
	// цикла по i, иначе одно и то же произведение d[c]·l[j][c] считалось бы
	// заново для каждой из dim−j строк. На матрице порядка сотни это как
	// раз та разница, из-за которой разложение перестаёт быть самым
	// дорогим местом решателя.
	dl := k.diagRow

	for j := 0; j < dim; j++ {
		rowJ := l[j*dim : j*dim+j]
		sum := m[j*dim+j]
		for c := 0; c < j; c++ {
			sum -= rowJ[c] * rowJ[c] * d[c]
		}
		if sum == 0 || math.IsNaN(sum) || math.IsInf(sum, 0) {
			return false
		}
		// Динамическая доводка: если ведущий элемент оказался исчезающе
		// мал или сменил ожидаемый знак, он подпирается до величины
		// регуляризации. Знак ожидаем по построению: первые n переменных
		// дают положительные ведущие элементы, последние p — отрицательные.
		want := 1.0
		if j >= k.n {
			want = -1.0
		}
		if math.Abs(sum) < k.delta || sum*want < 0 {
			sum = want * math.Max(k.delta, math.Abs(sum))
		}
		d[j] = sum

		dlj := dl[:j]
		for c := range dlj {
			dlj[c] = d[c] * rowJ[c]
		}
		inv := 1 / sum
		for i := j + 1; i < dim; i++ {
			rowI := l[i*dim : i*dim+j]
			s := m[i*dim+j]
			for c, v := range dlj {
				s -= rowI[c] * v
			}
			l[i*dim+j] = s * inv
		}
		l[j*dim+j] = 1
	}
	return true
}

// solveFactored решает L·D·Lᵀ·x = rhs (rhs и out могут совпадать).
func (k *kktSystem) solveFactored(rhs, out []float64) {
	dim := k.dim
	l, d := k.l, k.d
	copy(out, rhs)
	for i := 0; i < dim; i++ {
		s := out[i]
		for j := 0; j < i; j++ {
			s -= l[i*dim+j] * out[j]
		}
		out[i] = s
	}
	for i := 0; i < dim; i++ {
		out[i] /= d[i]
	}
	for i := dim - 1; i >= 0; i-- {
		s := out[i]
		for j := i + 1; j < dim; j++ {
			s -= l[j*dim+i] * out[j]
		}
		out[i] = s
	}
}

// solve решает систему с итерационным уточнением по нерегуляризованной
// матрице. Два уточняющих прохода — не подобранное число: регуляризация δ
// вносит относительную ошибку порядка δ/‖M‖, каждый проход давит её на тот
// же множитель, и двух хватает, чтобы уйти заведомо ниже допуска сходимости
// самого метода (см. Options.Tolerance).
func (k *kktSystem) solve(rhs, out []float64) {
	dim := k.dim
	k.solveFactored(rhs, out)
	for iter := 0; iter < 2; iter++ {
		k.symMulVec(k.orig, out, k.res)
		for i := 0; i < dim; i++ {
			k.res[i] = rhs[i] - k.res[i]
		}
		k.solveFactored(k.res, k.cor)
		for i := 0; i < dim; i++ {
			out[i] += k.cor[i]
		}
	}
}

// symMulVec вычисляет out = M·x для симметричной M, у которой заполнен
// только нижний треугольник.
func (k *kktSystem) symMulVec(m, x, out []float64) {
	dim := k.dim
	for i := range out {
		out[i] = 0
	}
	for i := 0; i < dim; i++ {
		row := m[i*dim : i*dim+i+1]
		s := 0.0
		xi := x[i]
		for j := 0; j < i; j++ {
			v := row[j]
			if v == 0 {
				continue
			}
			s += v * x[j]
			out[j] += v * xi
		}
		out[i] += s + row[i]*xi
	}
}

// sortInts — сортировка вставками короткого списка индексов. Списки здесь
// длиной в десятки элементов и почти упорядочены по построению (строки
// разреженной матрицы обходятся по возрастанию столбца), так что вставками
// это быстрее любой общей сортировки.
func sortInts(v []int) {
	for i := 1; i < len(v); i++ {
		x := v[i]
		j := i - 1
		for j >= 0 && v[j] > x {
			v[j+1] = v[j]
			j--
		}
		v[j+1] = x
	}
}
